import { defineConfig } from "vitest/config";
import type { Plugin } from "vite";
import react from "@vitejs/plugin-react";

// Production builds ship a strict Content Security Policy. The app makes no
// network requests at all, so connect-src is 'none', which blocks fetch, XHR,
// WebSockets and beacons. This is defense in depth, not a guarantee: CSP
// cannot block top-level navigation, so script that somehow ran in the page
// could still leak data that way. The primary control is script-src 'self'
// plus a ban on raw HTML and eval. Dev is exempt because Vite's HMR needs a
// websocket and inline scripts.
const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'none'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
].join("; ");

// Response headers for Cloudflare Pages, generated from the same CSP so the
// two can never drift. Sent as real HTTP headers they add what a <meta> CSP
// cannot: frame-ancestors (no clickjacking via iframes). Cloudflare reads
// dist/_headers at deploy time and does not serve it as a file.
// https://developers.cloudflare.com/pages/configuration/headers/
export const HEADERS = `# Generated by vite.config.ts. Edit the CSP there, not here.
/*
  Content-Security-Policy: ${CSP}; frame-ancestors 'none'
  X-Frame-Options: DENY
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  Cross-Origin-Opener-Policy: same-origin
  Strict-Transport-Security: max-age=31536000

# Vite fingerprints everything in /assets, so it can be cached forever.
/assets/*
  Cache-Control: public, max-age=31536000, immutable

# Keep preview deployments (per-branch and per-commit URLs) out of search results.
https://:version.:project.pages.dev/*
  X-Robots-Tag: noindex
`;

function securityHeaders(): Plugin {
  return {
    name: "fwc-security-headers",
    apply: "build",
    transformIndexHtml(html) {
      return html.replace(
        "<head>",
        `<head>\n    <meta http-equiv="Content-Security-Policy" content="${CSP}" />`,
      );
    },
    generateBundle() {
      this.emitFile({ type: "asset", fileName: "_headers", source: HEADERS });
    },
  };
}

export default defineConfig({
  plugins: [react(), securityHeaders()],
  build: { sourcemap: false },
  test: {
    globals: true,
    environment: "jsdom",
    setupFiles: ["src/test-setup.ts"],
  },
});
